"""T2 -- optimized offline feature computation into the two Gold Delta tables (guide s4).

Gate: **G3 Atomicity** -- "failed run khong de committed partial output" (guide s13). G3 is the
gate this module owns, but every later gate reads what it writes, so its declared surface is the
foundation for G1/G2/G4/G5/G6/G7/G9/G10 as well.

Guide s4.0 fixes two artifacts from one contract, and they are NOT interchangeable:

* ``pre_decision_features`` -- the aggregate immediately *before* each transaction. Training reads
  it (T4), and it is also the table Feast's ``FeatureView`` serves (guide s3.2.1), so T1 and T2
  have a real dependency.
* ``post_event_state_updates`` -- the aggregate *after* consuming each transaction. T5 materializes
  it into the online store. Guide s4.0: never materialize the latest ``pre_decision_features`` row,
  because it excludes the newest transaction and leaves online state one event behind.

Both are generated from the same FeatureSpec/reducer, and a fixture must prove the shift relation
between them (guide s4.0). The relation this module declares is
:data:`GOLD_SHIFT_RELATION` -- see it for the exact statement and its limits.

Two traps carried over from T1. They are written here because T2 repeats both at full scale.

**Trap 1 -- the feature table must be computed by the SQL ENGINE, never by the oracle.**
``features/paysim_recipient.py: paysim_pre_decision_feature_sql`` is the engine; it is imported,
never restated. ``features/paysim_reference.py`` is the pure-Python oracle and it is the
*expectation*, never the producer. A Gold table generated by the oracle and then compared against
the oracle is a tautology -- it checks one derivation against itself and G1/G3 would pass while
proving nothing. Two independent derivations (a DuckDB range self-join with ``DECIMAL(18,2)``
aggregation on one side, explicit ``decimal.Decimal`` loops on the other) is the only arrangement
in which agreement is evidence. Direction of authority when they disagree: the SQL is wrong until
proven otherwise (``paysim_reference.py`` module docstring). Never edit the expectation onto the
output.

**Trap 2 -- timestamps are computed in PYTHON, never in SQL.** ``event_timestamp`` and
``created_timestamp`` are the ADR-006 affine map of ``step``/``knowledge_step`` from
``EPOCH_0 = 2020-01-01T00:00:00Z``, and the single implementation is
``features/paysim_specs.py: paysim_step_to_timestamp`` (ADR-006 decision 1.7 -- exactly one
implementation, the constant is never re-typed). A DuckDB ``TIMESTAMPTZ`` expression renders
against the *session* time zone, so computing them in SQL makes the committed bytes depend on
which machine ran the build. Append them in Python, after the engine has produced the row.

Neither derived column is ever an input to the PIT computation. Eligibility, window bounds and the
replay tie-break stay on the integer ordinals ``(step, source_row_number)`` -- ADR-006 decision 1.4:
hour-resolution timestamps cannot express the tie-break at all, because every row in one ``step``
maps to the same instant.

Round-0 status: signatures, schemas and acceptance criteria only. Every body raises
``NotImplementedError``.
"""

