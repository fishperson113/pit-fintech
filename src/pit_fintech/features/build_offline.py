#: The shift relation guide s4.0 requires a fixture to prove, stated exactly.
#:
#: ``post_event_state_updates`` evaluates each window **inclusive of the current event**:
#: ``[step - window_hours + 1, step]``. ``pre_decision_features`` evaluates
#: ``[step - window_hours, step)``. For the same entity those two ranges coincide when the
#: pre-decision cutoff sits at ``step + 1``, so::
#:
#:     post_event_state(entity, step = s)  ==  pre_decision_history(entity, cutoff step = s + 1)
#:
#: **This holds only at a one-step shift.** A request at step ``s + k`` for ``k > 1`` reads an
#: online record whose window still ends at ``s``: the state is stale by construction, not wrong.
#: That is why guide s7.1 stores ``feature_timestamp`` and ``materialization_watermark`` on every
#: online record and s9.2 returns ``feature_status``. T6's G6 checkpoints replay only the events
#: strictly before ``e`` before comparing (guide s8.1 steps 2-3), which is the arrangement in which
#: parity is expected to be exact.
#:
#: **Open item for T5/T6** -- see the report: whether an entity with no event at ``s`` must have its
#: record advanced (a decay/refresh write) or be served stale-with-a-flag is not settled by the
#: guide. Do not decide it silently inside a materializer.
GOLD_SHIFT_RELATION: Final = (
    "post_event_state(entity, step=s) == pre_decision_history(entity, cutoff_step=s+1)"
)


def _assert_contract_alignment() -> None:
    """Fail at import if a Gold schema stops matching the frozen contract.

    Guard code, not business logic, and the same discipline
    ``paysim_reference._validate_contract_alignment`` and
    ``paysim_recipient.paysim_pre_decision_feature_sql`` already apply: field order is part of the
    contract (ADR-003), so drift must stop this module from loading rather than let seven
    downstream modules bind to a silently reshaped table.
    """

    declared = tuple(column.name for column in PRE_DECISION_FEATURE_SCHEMA)
    if declared[3:15] != PAYSIM_MODEL_FEATURE_ORDER:
        raise RuntimeError(
            "gold.pre_decision_features no longer carries the frozen twelve fields in contract "
            f"order: {declared[3:15]} != {PAYSIM_MODEL_FEATURE_ORDER}"
        )
    if GOLD_FEAST_SOURCE_COLUMNS[3:15] != PAYSIM_MODEL_FEATURE_ORDER:
        raise RuntimeError(
            "the Feast source projection no longer carries the frozen twelve fields in contract "
            f"order: {GOLD_FEAST_SOURCE_COLUMNS[3:15]} != {PAYSIM_MODEL_FEATURE_ORDER}"
        )
    if set(GOLD_FEAST_SOURCE_COLUMNS) - set(declared):
        raise RuntimeError(
            "the Feast source projection asks for columns gold.pre_decision_features does not "
            f"have: {sorted(set(GOLD_FEAST_SOURCE_COLUMNS) - set(declared))}"
        )
    if tuple(POST_EVENT_TO_CONTRACT_FIELD) != POST_EVENT_STATE_FIELD_NAMES:
        raise RuntimeError(
            "the post-event -> contract field map no longer covers the nine post-event fields in "
            f"order: {tuple(POST_EVENT_TO_CONTRACT_FIELD)} != {POST_EVENT_STATE_FIELD_NAMES}"
        )
    if tuple(POST_EVENT_TO_CONTRACT_FIELD.values()) != PAYSIM_HISTORY_FEATURE_NAMES:
        raise RuntimeError(
            "the post-event -> contract field map no longer targets the frozen history fields in "
            f"order: {tuple(POST_EVENT_TO_CONTRACT_FIELD.values())} != "
            f"{PAYSIM_HISTORY_FEATURE_NAMES}"
        )


_assert_contract_alignment()


