@dataclass(frozen=True, slots=True, kw_only=True)
class SameStepTieProbe:
    """Whether the built range contains any same-``step`` pair, and where.

    **This exists because of a hole T1 left open.** Guide s8.3 lists "at least one same-second tie
    case" among G6's required checkpoints, and T1's Feast integration never touched one: the
    committed fixture feature table has 11 rows carrying 11 distinct ``event_timestamp`` values, so
    the tie path has never been exercised through Feast at all. When T2 builds Gold from full
    Silver the first thing it must do is *measure* whether an in-scope same-step pair exists.

    Do not assume one does. Under ADR-006 every row in a ``step`` maps to the same instant, so a
    same-step pair is exactly the "same-second tie" G6 asks for -- but only pairs that are both
    in the scoring scope and share a destination entity actually exercise the strict ``<``
    predicate. If :attr:`in_scope_same_step_pairs` comes back ``0``, that is a finding to report to
    T6, not a number to route around: G6 cannot claim the checkpoint on a range that has no tie.
    """

    #: Cutoff rows sharing ``(destination_entity_id, step)`` with at least one other in-scope row.
    in_scope_same_step_pairs: int
    #: Same, without the scoring-scope filter -- a same-step pair where the other row is out of
    #: scope still exercises the history-side predicate, which is a weaker but real tie case.
    any_same_step_pairs: int
    #: Distinct entities involved, so T6 can pick a checkpoint entity deterministically.
    entities_with_same_step_pairs: int
    #: Deterministic, id-ordered examples for T6 to pin a checkpoint on:
    #: ``(destination_entity_id, step, source_row_number)``.
    examples: tuple[tuple[str, int, int], ...]


